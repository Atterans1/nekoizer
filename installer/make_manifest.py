"""Write installer/manifest.json and build_meta.py for a build.  python installer/make_manifest.py [VERSION]

manifest.json records the SHA256 and size of every shipped config file (including installer/torch_lib_manifest.json, the list of PyTorch
runtime libraries) and the URL, size and SHA256 of every model file the first run downloads (from installer/model_sources.json).
build_meta.py bakes the version and the SHA256 of manifest.json into the executable, so the torch library list is covered by that chain.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from integrity import Sha256File  # noqa: E402

# ---------------------------------------------------------------- PUBLIC
SOURCES = ROOT / "installer" / "model_sources.json"
MANIFEST = ROOT / "installer" / "manifest.json"
TORCH_LIB_MANIFEST = ROOT / "installer" / "torch_lib_manifest.json"  # written by tools/make_torch_manifest.py
BUILD_META = ROOT / "build_meta.py"


def ShippedKey(entry: dict) -> str:
    """Path of a shipped file inside the app folder: its destination folder plus its own name."""
    return f"{entry['dest']}/{Path(entry['src']).name}"


def Build(version: str) -> str:
    """Write both files and return the SHA256 of manifest.json."""
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    files = {}
    for entry in sources["shipped"]:
        path = ROOT / entry["src"]
        files[ShippedKey(entry)] = {"size": path.stat().st_size, "sha256": Sha256File(path)}
    if not TORCH_LIB_MANIFEST.exists():
        raise SystemExit("installer/torch_lib_manifest.json is missing: run tools/make_torch_manifest.py first")
    torch_lib = json.loads(TORCH_LIB_MANIFEST.read_text(encoding="utf-8"))
    doc = {"version": version, "seedvc_commit": sources["seedvc_commit"], "files": files, "models": sources["models"],
           "torch_lib": {"wheel_url": torch_lib["wheel"]["url"], "wheel_size": torch_lib["wheel"]["size"], "members": len(torch_lib["files"]),
                         "sha256": Sha256File(TORCH_LIB_MANIFEST)}}
    raw = (json.dumps(doc, indent=1, sort_keys=True) + "\n").encode("utf-8")
    MANIFEST.write_bytes(raw)
    digest = hashlib.sha256(raw).hexdigest()
    BUILD_META.write_text(f'"""Generated by installer/make_manifest.py. Do not edit."""\nVERSION = "{version}"\nMANIFEST_SHA256 = "{digest}"\n', encoding="utf-8")
    return digest


if __name__ == "__main__":
    print(Build(sys.argv[1] if len(sys.argv) > 1 else "1.0.0"))
