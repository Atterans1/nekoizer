"""Where the app finds its shipped files and where it keeps user data.

A packaged (PyInstaller) build reads its shipped files from the bundle folder and keeps everything the user owns (downloaded
models, the verification cache, logs) under %LOCALAPPDATA%\\Nekoizer, which the uninstaller leaves alone. A source tree keeps
using the repository's assets/seedvc folder for the models. S2S_DATA_DIR moves the user-data folder (tests, portable use).
"""
from __future__ import annotations

import os
import sys
from pathlib import Path
from types import ModuleType

# ---------------------------------------------------------------- PUBLIC
PRODUCT = "Nekoizer"
DATA_DIR_ENV = "S2S_DATA_DIR"
DEV_VERSION = "0.0.0-dev"


def IsFrozen() -> bool:
    return bool(getattr(sys, "frozen", False))


def AppDir() -> Path:
    """The folder that holds the shipped files: the PyInstaller bundle folder, or the repository root."""
    if IsFrozen():
        return Path(getattr(sys, "_MEIPASS", None) or Path(sys.executable).resolve().parent)
    return Path(__file__).resolve().parent


def DataDir() -> Path:
    override = os.environ.get(DATA_DIR_ENV)
    if override:
        return Path(override)
    local = os.environ.get("LOCALAPPDATA")
    return (Path(local) if local else Path.home() / "AppData" / "Local") / PRODUCT


def ModelsDir() -> Path:
    """Where the Seed-VC model files live: the user-data folder for the packaged app, assets/seedvc in a plain source tree."""
    if IsFrozen() or os.environ.get(DATA_DIR_ENV):
        return DataDir() / "models"
    return AppDir() / "assets" / "seedvc"


def ManifestPath() -> Path:
    return AppDir() / "manifest.json" if IsFrozen() else AppDir() / "installer" / "manifest.json"


def Version() -> str:
    meta = _BuildMeta()
    return meta.VERSION if meta is not None else DEV_VERSION


def BakedManifestSha256() -> str | None:
    """The SHA256 of manifest.json recorded at build time, or None in a source tree."""
    meta = _BuildMeta()
    return meta.MANIFEST_SHA256 if meta is not None else None


# ---------------------------------------------------------------- PRIVATE
def _BuildMeta() -> ModuleType | None:
    """build_meta.py is generated by installer/make_manifest.py and bundled by build_exe.py; a source tree has none."""
    try:
        import build_meta
    except ModuleNotFoundError:
        return None
    return build_meta
